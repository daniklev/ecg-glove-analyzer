class HiPassFilter:
    """
    Legacy recursive high-pass filter replicating Java HiPassFilter.
    Supports HP005, HP015, HP05 types.
    """

    _COEFFS = {
        "HP05": {"HP0": -0.9878018507, "HP1": 1.9877269954, "GAIN": 1.006155446},
        "HP015": {"HP0": -0.9963349287, "HP1": 1.9963282000, "GAIN": 1.001837588},
        "HP005": {"HP0": -0.9987734371, "HP1": 1.9987726844, "GAIN": 1.00061384},
    }

    def __init__(self, ftr_type: str):
        if ftr_type not in self._COEFFS:
            raise ValueError(f"Unsupported HP filter type {{ftr_type}}")
        coeffs = self._COEFFS[ftr_type]
        self.HP0 = coeffs["HP0"]
        self.HP1 = coeffs["HP1"]
        self.GAIN = coeffs["GAIN"]
        # shift registers for xv and yv (length NPOLES+2 = 4)
        self.xv = [0.0] * 4
        self.yv = [0.0] * 4

    def filter_sample(self, val: float) -> float:
        # shift and scale input
        self.xv[0], self.xv[1], self.xv[2] = self.xv[1], self.xv[2], val / self.GAIN
        # shift output history
        self.yv[0], self.yv[1] = self.yv[1], self.yv[2]
        # compute new output
        self.yv[2] = (
            (self.xv[0] + self.xv[2])
            - 2 * self.xv[1]
            + self.HP0 * self.yv[0]
            + self.HP1 * self.yv[1]
        )
        return self.yv[2]


class Buffer:
    """
    Circular buffer storing recent values, tracking sum and non-zero count.
    """

    def __init__(self, size: int):
        self.size = size
        self.buffer = [0.0] * size
        self.start = 0
        self.filling = 0
        self.sum = 0.0
        self.count = 0

    def fill(self) -> bool:
        return self.filling == self.size

    def add(self, x: float) -> None:
        if self.filling == self.size:
            old = self.buffer[self.start]
            self.sum -= old
            if old != 0.0:
                self.count -= 1
            self.buffer[self.start] = x
            self.sum += x
            if x != 0.0:
                self.count += 1
            self.start = (self.start + 1) % self.size
        else:
            self.buffer[self.start] = x
            self.sum += x
            if x != 0.0:
                self.count += 1
            self.filling += 1
            self.start = (self.start + 1) % self.size

    def get_avg(self) -> float:
        return 0.0 if self.count == 0 else self.sum / self.count

    def get_start(self) -> float:
        return self.buffer[self.start]


class MorphologyFilter:
    """
    Implements the legacy MorphologyFilterClass.computeHPF logic sample-by-sample.
    """

    def __init__(self, delta_threshold: float = 5.0):
        self.InputBufferSize = 150
        self.AvgBufferSize = 250
        self.LPFBufferSize = 10
        self.DelayBufferSize = (
            self.InputBufferSize + self.AvgBufferSize + self.LPFBufferSize
        ) // 2

        self.input = Buffer(self.InputBufferSize)
        self.avg1 = Buffer(self.AvgBufferSize)
        self.lpf = Buffer(self.LPFBufferSize)
        self.delay = Buffer(self.DelayBufferSize)

        self.old_data = 0.0
        self.delta_threshold = delta_threshold

    def compute_hpf(self, data: float) -> float:
        value = 0.0
        # delay store
        self.delay.add(data)
        # low-pass smoothing
        self.lpf.add(data)
        # thresholded input buffer
        if abs(data - self.old_data) < self.delta_threshold:
            self.input.add(self.lpf.get_avg())
        else:
            self.input.add(0.0)
        self.old_data = data
        if self.input.fill():
            self.avg1.add(self.input.get_avg())
            if self.avg1.fill():
                value = self.delay.get_start() - self.avg1.get_avg()
        return value


