    def __init__(self, hp_type: str = "HP05"):
        # instantiate recursive HP filter
        self.hp_filter = HiPassFilter(hp_type)
        # instantiate morphology filter
        self.morph_filter = MorphologyFilter()

    def high_pass_sample(self, data: float) -> float:
        """
        Apply legacy recursive HP filter to single sample.
        """
        return self.hp_filter.filter_sample(data)

    def notch(self, signal: np.ndarray, freq: int) -> np.ndarray:
        """
        Apply legacy FIR notch filter at freq Hz using convolution.
        """
        coeffs = self._FIR_COEFFS.get(freq)
        if coeffs is None:
            raise ValueError(f"Unsupported notch frequency {freq}")
        return np.convolve(signal, coeffs, mode="same")

    def morphology_hpf_sample(self, data: float) -> float:
        """
        Apply sample-by-sample morphological HPF pipeline.
        """
        return self.morph_filter.compute_hpf(data)

    def process_signal(
        self, signal: np.ndarray, notch_freqs: list[int] = []
    ) -> np.ndarray:
        """
        Process full signal: HP -> notch(s) -> morphology HPF.
        notch_freqs: list of notch frequencies to apply sequentially
        """
        # vectorize recursive HP by iterative filtering per sample
        hp_out = np.array([self.high_pass_sample(x) for x in signal])
        out = hp_out
        if notch_freqs:
            for f in notch_freqs:
                out = self.notch(out, f)
        # morphology HPF per sample
        morph_out = np.array([self.morphology_hpf_sample(x) for x in out])
        return morph_out
